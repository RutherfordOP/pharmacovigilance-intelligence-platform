CREATE OR REPLACE TABLE PV_PLATFORM.CURATED.AE_SIGNAL_FLAGS AS
WITH stats AS (
  SELECT
    drug_ndc_code,
    AVG(ae_count) AS avg_count,
    STDDEV(ae_count) AS stddev_count
  FROM PV_PLATFORM.CURATED.VW_MONTHLY_AE_BY_DRUG
  GROUP BY drug_ndc_code
)
SELECT
  v.drug_ndc_code,
  v.drug_name,
  v.period_start,
  v.ae_count,
  s.avg_count,
  s.stddev_count,
  (v.ae_count - s.avg_count) / NULLIF(s.stddev_count, 0) AS z_score,
  CASE WHEN ABS((v.ae_count - s.avg_count) / NULLIF(s.stddev_count, 0)) > 2 THEN TRUE ELSE FALSE END AS is_anomaly,
  CURRENT_TIMESTAMP() AS run_ts
FROM PV_PLATFORM.CURATED.VW_MONTHLY_AE_BY_DRUG v
JOIN stats s ON v.drug_ndc_code = s.drug_ndc_code
ORDER BY ABS(z_score) DESC NULLS LAST;


SELECT * FROM PV_PLATFORM.CURATED.AE_SIGNAL_FLAGS WHERE is_anomaly = TRUE;

