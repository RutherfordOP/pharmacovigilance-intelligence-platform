CREATE OR REPLACE VIEW PV_PLATFORM.CURATED.VW_SERIOUS_RATE_BY_COUNTRY AS
SELECT
  g.country,
  dt.year,
  dt.month,
  DATE_FROM_PARTS(dt.year, dt.month, 1) AS period_start,
  COUNT(*) AS total_reports,
  SUM(CASE WHEN f.event_seriousness = 'Serious' THEN 1 ELSE 0 END) AS serious_reports,
  ROUND(
    SUM(CASE WHEN f.event_seriousness = 'Serious' THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0) * 100.0,
    1
  ) AS serious_rate_pct
FROM PV_PLATFORM.CURATED.FACT_ADVERSE_EVENT f
JOIN PV_PLATFORM.CURATED.DIM_GEOGRAPHY g ON f.geo_key = g.geo_key
JOIN PV_PLATFORM.CURATED.DIM_DATE dt ON f.report_date_key = dt.date_key
GROUP BY g.country, dt.year, dt.month
ORDER BY g.country, period_start;

SELECT * FROM PV_PLATFORM.CURATED.VW_SERIOUS_RATE_BY_COUNTRY ORDER BY serious_rate_pct DESC;



